/*
 * ReverieCoreIccData - 导出 .kra 时逐层内嵌的 sRGB ICC 档案
 *
 * SPDX-License-Identifier: GPL-3.0-or-later
 *
 * ---------------------------------------------------------------------------
 * 为什么需要它
 * ---------------------------------------------------------------------------
 * 桌面 Krita 载入 .kra 时, KisKraLoadVisitor::visit(KisPaintLayer*) 会对每个
 * paint layer 无条件读 <layer>.icc (kis_kra_load_visitor.cpp:194 -> loadProfile()
 * :626), 文件缺失或无法解析就往警告列表里塞一条
 * "Could not load profile: <path>." (中文: 无法加载色彩特性文件)。
 *
 * 上游实现是写 colorSpace()->profile()->rawData(), 但 Android 移植版的色彩空间
 * 全部走 KoSimpleColorSpace: KoSimpleColorSpaceFactory::createColorProfile()
 * 直接返回 0, KoColorProfile::rawData() 也只有返回空 QByteArray 的默认实现
 * (libs/pigment/KoColorProfile.h:208), 没有任何子类覆写 —— 所以照搬上游写法在
 * 这里恒等于"一个字节都不写", 警告必然出现。
 *
 * ---------------------------------------------------------------------------
 * 数据从哪来
 * ---------------------------------------------------------------------------
 * 由 lcms2 的 cmsCreate_sRGBProfile() + cmsSaveProfileToMem() 生成 (lcms2 为 MIT
 * 许可, 生成物不含第三方版权内容), 588 字节, 已验证:
 *   - ICC 头 class='mntr' space='RGB ' pcs='XYZ '
 *   - cmsOpenProfileFromMem() 可打开
 *   - rTRC 为标准 sRGB 传递曲线 (eval(0.5)=0.21404, 与 Krita 官方模板内嵌的
 *     sRGB-elle-V2-srgbtrc.icc 一致; 注意不要用 krita25_lcms-builtin-sRGB_
 *     g100-truegamma.icc, 那条是 gamma 1.0 线性曲线)
 * 与位深无关, 8bit / 16bit 图层共用同一份。
 */

